// Regenerate ExampleSources.kt from pytoy's canonical examples/ (pytoy is the
// source of truth). Gradle's input/output tracking runs this only when an
// example or the generator actually changed, so repeated builds skip it. If the
// pytoy checkout isn't present (e.g. ktoy cloned alone), the task is skipped and
// the committed ExampleSources.kt is used as-is.
val pytoyDir = file(providers.environmentVariable("PYTOY").orElse(
    rootProject.projectDir.parentFile.resolve("pytoy").absolutePath))
val genExamples = tasks.register<Exec>("genExampleSources") {
    val examplesDir = pytoyDir.resolve("examples")
    onlyIf { examplesDir.isDirectory }
    if (examplesDir.isDirectory) {
        inputs.dir(examplesDir)
    }
    inputs.file(rootProject.projectDir.resolve("scripts/gen_example_sources.py"))
    outputs.file(layout.projectDirectory.file(
        "src/commonMain/kotlin/org/bytefred/ktoy/core/ExampleSources.kt"))
    workingDir = rootProject.projectDir
    environment("PYTOY", pytoyDir.absolutePath)
    commandLine("python3", "scripts/gen_example_sources.py")
}

// Run the generator before any Kotlin source is compiled.
tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompilationTask<*>>().configureEach {
    dependsOn(genExamples)
}

// ── build-time version info (GeneratedVersionInfo.kt) ───────────────────────
// Ported from OpenYarnStash: the version number comes from gradle.properties,
// commit sha / dirty / commit-date from git. Written into commonMain so every
// target (incl. iOS and web, where runtime git isn't available) can show it in
// Help -> About. Bump the version in gradle.properties.
abstract class GenerateVersionInfo @Inject constructor(
    private val execOps: ExecOperations,
) : DefaultTask() {
    @get:InputDirectory @get:Optional @get:PathSensitive(PathSensitivity.NONE)
    abstract val gitDir: DirectoryProperty
    @get:Input abstract val versionName: Property<String>
    @get:Input abstract val packageName: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun run() {
        val version = versionName.get()
        var sha = "unknown"
        var isDirty = "unknown"
        var commitDate = "unknown"
        val wd = gitDir.asFile.orNull?.parentFile ?: project.rootDir
        if (gitDir.asFile.orNull?.exists() == true) {
            try {
                fun git(vararg args: String): String {
                    val out = ByteArrayOutputStream()
                    execOps.exec {
                        workingDir = wd
                        commandLine(listOf("git", *args))
                        standardOutput = out
                        isIgnoreExitValue = false
                    }
                    return out.toString().trim()
                }
                sha = git("rev-parse", "--short", "HEAD")
                commitDate = git("log", "-1", "--format=%cI", "--date=iso-strict")
                isDirty = if (git("status", "--porcelain", "--untracked-files=no")
                        .isEmpty()) "clean" else "dirty"
            } catch (e: Exception) {
                // git unavailable (e.g. a tarball build): keep the defaults
            }
        }
        val df = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'")
        df.timeZone = TimeZone.getTimeZone("UTC")
        val buildDate = df.format(Date())
        val commitYear = commitDate.take(4).toIntOrNull() ?: 0
        val dir = outputDir.get().asFile.apply { mkdirs() }
        dir.resolve("GeneratedVersionInfo.kt").writeText(
            """
            package ${packageName.get()}

            /**
             * AUTO-GENERATED — DO NOT EDIT.
             * Generated at build time by the generateVersionInfo Gradle task.
             * Change the version in gradle.properties (version=X.Y.Z); the rest
             * comes from git. Shown in Help -> About.
             */
            object GeneratedVersionInfo {
                const val VERSION: String = "$version"
                const val COMMIT_SHA: String = "$sha"
                const val COMMIT_DATE: String = "$commitDate"
                const val COMMIT_YEAR: Int = $commitYear
                const val IS_DIRTY: String = "$isDirty"
                const val BUILD_DATE: String = "$buildDate"
            }
            """.trimIndent() + "\n"
        )
    }
}

val generateVersionInfo = tasks.register("generateVersionInfo", GenerateVersionInfo::class.java) {
    val gitDirFile = rootProject.layout.projectDirectory.dir(".git")
    if (gitDirFile.asFile.exists()) gitDir.set(gitDirFile)
    versionName.set(project.provider { project.version.toString() })
    packageName.set("org.bytefred.ktoy")
    outputDir.set(layout.buildDirectory.dir("generated/versionInfo"))
}

tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompilationTask<*>>().configureEach {
    dependsOn(generateVersionInfo)
}
