#!/usr/bin/env python3
"""
Generate ktoy's MiniCExamples.kt from the pytoy C example programs, using the
MINIMAL compiler minicc (pytoy/minicc.py) as the oracle.

For every examples/c/**/*.toyc in the sibling pytoy checkout that minicc ACCEPTS
(EXCLUDING 04-io/, which uses read/write I/O and can't run headless-
deterministically), this embeds a triple:
    name -> (cSource, expectedToys)
where expectedToys is pytoy minicc's compile_source(src, name) output — the
golden, byte-for-byte reference ktoy's compileSourceMini must reproduce.

An example is "accepted" iff it BOTH compiles under pytoy minicc without raising
MiniError AND the produced assembly assembles with no errors inside the 240-byte
program region. Compiling alone is not enough: minicc inlines everything (no real
calls), so an accepted program can still overflow the Machine and never run — such
examples are skipped too. Recursive examples and any using unsupported syntax are
left out automatically.

The source name handed to compile_source appears in the "# Generated by minicc
from <name>" header, so it must match between pytoy and ktoy. We use
os.path.basename(path) WITH the .toyc extension, exactly like gen_c_examples.py.

pytoy is a sibling of this repo (../pytoy), overridable with PYTOY:
    python3 scripts/gen_minicc_examples.py
    PYTOY=/path/to/pytoy python3 scripts/gen_minicc_examples.py
"""

import os
import sys
import glob

KTOY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PYTOY = os.environ.get("PYTOY", os.path.join(os.path.dirname(KTOY), "pytoy"))
C_DIR = os.path.join(PYTOY, "examples", "c")
OUT = os.path.join(KTOY, "composeApp", "src", "commonTest", "kotlin",
                   "org", "bytefred", "ktoy", "core", "MiniCExamples.kt")


def kotlin_triple_string(s):
    """Embed s in a Kotlin raw (triple-quote) string. Raw strings can't contain
    a literal triple-quote or a $ (interpolation); guard against both so a future
    example that breaks the embedding fails loudly here, not in the Kotlin build."""
    if '"""' in s:
        raise ValueError("content contains a triple-quote; can't embed raw")
    if '$' in s:
        raise ValueError("content contains '$'; would break Kotlin interpolation")
    return f'"""{s}"""'


def main():
    if not os.path.isdir(C_DIR):
        raise SystemExit(
            f"pytoy C examples not found at {C_DIR}. "
            f"Clone pytoy next to ktoy, or set PYTOY=/path/to/pytoy.")

    sys.path.insert(0, PYTOY)
    from pytoy.minicc import compile_source, MiniError  # noqa: E402
    from pytoy.assembler import assemble  # noqa: E402

    entries = []
    skipped = []
    for path in sorted(glob.glob(os.path.join(C_DIR, "**", "*.toyc"),
                                 recursive=True)):
        # 04-io uses read()/write() memory-mapped I/O: not headless-deterministic.
        if os.sep + "04-io" + os.sep in path:
            continue
        name = os.path.basename(path)          # e.g. "sum3.toyc"
        with open(path) as f:
            src = f.read()
        try:
            asm = compile_source(src, name)    # golden reference assembly
        except MiniError as e:
            skipped.append((name, str(e)))
            continue
        except Exception as e:                 # noqa: BLE001
            skipped.append((name, f"{type(e).__name__}: {e}"))
            continue
        # Compiling is not enough: minicc inlines everything, so the assembly can
        # still overflow the 240-byte program region and never run. Require it to
        # assemble cleanly before embedding.
        try:
            _, _, _, _, asm_errors, _ = assemble(asm)
        except Exception as e:                 # noqa: BLE001
            skipped.append((name, f"assemble raised {type(e).__name__}: {e}"))
            continue
        if asm_errors:
            skipped.append((name, "; ".join(str(x) for x in asm_errors)))
            continue
        entries.append((name, src, asm))

    lines = [
        "package org.bytefred.ktoy.core",
        "",
        "/**",
        " * minicc verification fixtures, embedded as strings (commonTest has no",
        " * portable filesystem access).",
        " *",
        " * For each example: the C source and the GOLDEN .toys produced by pytoy's",
        " * minicc compile_source(src, name). ktoy's compileSourceMini(src, name)",
        " * must reproduce the golden output byte-for-byte. The `name` is the .toyc",
        " * file basename (with extension), so the \"# Generated by minicc from",
        " * <name>\" headers agree.",
        " *",
        " * Only the examples minicc ACCEPTS are embedded (probed by actually",
        " * compiling with pytoy minicc, exactly like examples_index). Recursive and",
        " * unsupported-syntax examples are left out automatically. 04-io/ examples",
        " * are excluded (read/write I/O, not headless-deterministic).",
        " *",
        " * GENERATED from pytoy examples/c/ by scripts/gen_minicc_examples.py — do",
        " * not edit by hand; regenerate when the C examples or minicc change.",
        " */",
        "",
        "val MINICC_EXAMPLES: List<CExample> = listOf(",
    ]
    for name, src, asm in entries:
        lines.append(f'    CExample(')
        lines.append(f'        name = {kotlin_triple_string(name)},')
        lines.append(f'        cSource = {kotlin_triple_string(src)},')
        lines.append(f'        expectedToys = {kotlin_triple_string(asm)},')
        lines.append(f'    ),')
    lines.append(")")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT} ({len(entries)} examples)")
    print("accepted:", ", ".join(n for n, _, _ in entries))
    print("skipped (minicc rejects):")
    for name, why in skipped:
        print(f"  {name}: {why}")


if __name__ == "__main__":
    main()
